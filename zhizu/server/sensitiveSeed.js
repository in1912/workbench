function seedSensitive() {
  const wCount = db.prepare('SELECT COUNT(*) c FROM sensitive_words').get().c;
  if (wCount === 0) {
    const ins = db.prepare('INSERT INTO sensitive_words(word,platform,category,severity,description,suggestion) VALUES(?,?,?,?,?,?)');
    db.exec('BEGIN');
    try {
      const seen = new Set();
      for (const w of SEED_WORDS) {
        const k = w.platform + '|' + w.word;
        if (seen.has(k)) continue;
        seen.add(k);
        ins.run(w.word, w.platform, w.category, w.severity, w.description, w.suggestion);
      }
      db.exec('COMMIT');
    } catch (e) { db.exec('ROLLBACK'); throw e; }
  }
  const rCount = db.prepare('SELECT COUNT(*) c FROM regs').get().c;
  if (rCount === 0) {
    const ins = db.prepare('INSERT INTO regs(title,category,issuer,doc_no,publish_date,effective_date,summary,key_points,url,note) VALUES(?,?,?,?,?,?,?,?,?,?)');
    db.exec('BEGIN');
    try {
      for (const r of SEED_REGS) {
        ins.run(r.title, r.category, r.issuer, r.doc_no, r.publish_date, r.effective_date,
          r.summary, JSON.stringify(r.key_points || []), r.url, r.note || '');
      }
      db.exec('COMMIT');
    } catch (e) { db.exec('ROLLBACK'); throw e; }
  }
}

module.exports = { seedSensitive, SEED_WORDS, SEED_REGS };
