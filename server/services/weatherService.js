// 归一化 + 后缀剥离匹配：「青岛市」→「青岛」，「锡林郭勒盟」→「锡林郭勒」再回退全名
const SUFFIXES = ['特别行政区', '自治州', '自治区', '地区', '盟', '市', '省'];
function lookupCity(input) {
  let n = String(input || '').trim().replace(/\s+/g, '');
  for (let i = 0; i < 3 && n; i++) {
    if (CITY_DICT[n]) return { name: n, lon: CITY_DICT[n][0], lat: CITY_DICT[n][1] };
    const suf = SUFFIXES.find((s) => n.endsWith(s) && n.length > s.length);
    if (!suf) break;
    n = n.slice(0, -suf.length);
  }
  return null;
}

// undici 的 "fetch failed" 不带原因码，真实原因藏在 e.cause（ENOTFOUND/ETIMEDOUT/ECONNRESET/证书错误…）
const failCause = (e) => (e?.cause?.code || e?.cause?.message || e?.message || '未知原因');

// Open-Meteo 免费接口：无 key、按经纬度返回 7 天预报
async function fetchWeather(d) {
  const cfg = getSetting(d, 'weather', {});
  if (!cfg.lat || !cfg.lon) {
    return { ok: false, error: '尚未配置城市（请在设置中填写城市或经纬度）' };
  }
  const url =
    'https://api.open-meteo.com/v1/forecast?' +
    `latitude=${cfg.lat}&longitude=${cfg.lon}` +
    '&current=temperature_2m,relative_humidity_2m,weather_code,wind_speed_10m' +
    '&daily=weather_code,temperature_2m_max,temperature_2m_min,precipitation_probability_max,sunrise,sunset' +
    '&timezone=auto&forecast_days=7';
  let res;
  try {
    res = await fetch(url, { signal: AbortSignal.timeout(20000) });
  } catch (e) {
    throw new Error(`天气服务连接失败（${failCause(e)}）——NAS 服务器无法访问 api.open-meteo.com，请检查 NAS 外网/DNS`);
  }
  if (!res.ok) throw new Error('天气接口错误 ' + res.status);
  return await res.json();
}


